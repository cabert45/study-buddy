export function nomExercice(mode) {
  if (!mode) return '';
  if (NOMS[mode]) return NOMS[mode];
  const v = /^verbe_semaine:([a-zé]+)_(\w+)$/.exec(mode);
  if (v) return `Mon verbe — ${v[1]} (${v[2].replace('present', 'présent').replace('_', ' ')})`;
  if (mode.startsWith('dictee_flashcard')) return 'Dictée — cartes';
  return mode.replace(/_/g, ' ').replace(/^./, (c) => c.toUpperCase());
}
